import { randomUUID, createHash } from "node:crypto";
import { describe, it, expect, beforeAll, afterAll } from "vitest";
import { Pool } from "pg";
import { upsertMediaAsset, findMediaAssetByHash, MediaAssetInput } from "../../src/modules/mediaAssets/repository";

const RUN = process.env.RUN_DB_TESTS === "1";
const TRIPC_WORKSPACE = "10000000-0000-4000-8000-000000000001";

describe.skipIf(!RUN)("Live DB Integration: media_assets persistence & idempotency", () => {
  let pool: Pool;

  beforeAll(() => {
    const connStr =
      process.env.DATABASE_URL ||
      "postgres://ai_growth_dev:ae5a9cb1e19ca954422a6aca20206537f63c9e716a051c1f250bac717c74d4b9@127.0.0.1:15432/ai_growth_os";
    pool = new Pool({ connectionString: connStr });
  });

  afterAll(async () => {
    if (pool) {
      await pool.end();
    }
  });

  it("tạo bản ghi media_assets đầy đủ các trường từ ảnh guardrail & storage client", async () => {
    const rawImageBytes = Buffer.from("SYNTHETIC_WEBP_IMAGE_BYTES_FOR_TEST_" + Date.now());
    const contentHash = createHash("sha256").update(rawImageBytes).digest("hex");
    const filename = `${contentHash.slice(0, 16)}_1x1.webp`;
    const storageKey = `generated/${filename}`;
    const storageUrl = `http://localhost:3000/uploads/${storageKey}`;

    const input: MediaAssetInput = {
      workspace_id: TRIPC_WORKSPACE,
      source_type: "ai_generated",
      is_ai_generated: true,
      url: storageUrl,
      storage_key: storageKey,
      prompt: "A beautiful coastal scene in Da Nang at dawn, soft natural light",
      model_name: "Juggernaut XL v9",
      seed: 424242,
      cost_usd: 0.0,
      width: 1024,
      height: 1024,
      license: "ai_generated",
      attribution: "Generated by Juggernaut XL v9 via AI Growth OS",
      status: "approved",
      content_hash: contentHash,
      alt_text: "[Ảnh minh họa AI] Bình minh bờ biển Đà Nẵng",
    };

    const record = await upsertMediaAsset(input);

    expect(record).toBeDefined();
    expect(record.workspace_id).toBe(TRIPC_WORKSPACE);
    expect(record.source_type).toBe("ai_generated");
    expect(record.url).toBe(storageUrl);
    expect(record.content_hash).toBe(contentHash);
    expect(record.status).toBe("approved");

    // Verify metadata JSONB fallback holds all requested fields
    const meta = (record.ai_metadata as any) || {};
    expect(meta.prompt).toBe(input.prompt);
    expect(meta.model_name).toBe("Juggernaut XL v9");
    expect(meta.seed).toBe(424242);
    expect(meta.cost_usd).toBe(0.0);
    expect(meta.width).toBe(1024);
    expect(meta.height).toBe(1024);
    expect(meta.storage_key).toBe(storageKey);
  });

  it("đảm bảo idempotent: gọi lưu cùng content_hash nhiều lần không sinh bản ghi trùng", async () => {
    const rawImageBytes = Buffer.from("IDEMPOTENCY_TEST_BYTES_" + Date.now());
    const contentHash = createHash("sha256").update(rawImageBytes).digest("hex");
    const storageKey = `generated/${contentHash.slice(0, 16)}_1x1.webp`;
    const storageUrl = `http://localhost:3000/uploads/${storageKey}`;

    const input: MediaAssetInput = {
      workspace_id: TRIPC_WORKSPACE,
      source_type: "ai_generated",
      is_ai_generated: true,
      url: storageUrl,
      storage_key: storageKey,
      prompt: "Idempotent duplicate check prompt",
      model_name: "Juggernaut XL v9",
      seed: 999,
      cost_usd: 0.0,
      width: 1024,
      height: 1024,
      license: "ai_generated",
      attribution: "Generated by Juggernaut XL v9",
      status: "approved",
      content_hash: contentHash,
      alt_text: "[Ảnh minh họa AI] Idempotent image",
    };

    // First insert
    const record1 = await upsertMediaAsset(input);
    expect(record1.content_hash).toBe(contentHash);

    // Second insert with different ID attempt
    const record2 = await upsertMediaAsset({
      ...input,
      id: randomUUID(), // Caller generates a new ID, but content_hash is the same
    });

    // Idempotency check: returns the same record ID
    expect(record2.id).toBe(record1.id);
    expect(record2.content_hash).toBe(record1.content_hash);

    // DB count check: exactly 1 row exists for this (workspace_id, content_hash)
    const countRes = await pool.query(
      "SELECT COUNT(*) FROM media_assets WHERE workspace_id = $1 AND content_hash = $2",
      [TRIPC_WORKSPACE, contentHash]
    );
    expect(parseInt(countRes.rows[0].count, 10)).toBe(1);
  });

  it("kiểm tra xác thực Migration 023 trong transaction: thêm cột, unique constraint và ON CONFLICT", async () => {
    const client = await pool.connect();
    try {
      await client.query("BEGIN");

      // Apply migration 023 DDL in the transaction
      await client.query(`
        ALTER TABLE media_assets
            ADD COLUMN IF NOT EXISTS storage_key TEXT,
            ADD COLUMN IF NOT EXISTS prompt TEXT,
            ADD COLUMN IF NOT EXISTS model_name VARCHAR(100),
            ADD COLUMN IF NOT EXISTS seed BIGINT,
            ADD COLUMN IF NOT EXISTS cost_usd NUMERIC(10, 4) DEFAULT 0.0,
            ADD COLUMN IF NOT EXISTS width INTEGER,
            ADD COLUMN IF NOT EXISTS height INTEGER,
            ADD COLUMN IF NOT EXISTS is_ai_generated BOOLEAN DEFAULT FALSE;

        CREATE UNIQUE INDEX IF NOT EXISTS uq_media_assets_workspace_content_hash
            ON media_assets(workspace_id, content_hash)
            WHERE content_hash IS NOT NULL;
      `);

      const testHash = createHash("sha256").update("MIGRATION_023_TEST_" + Date.now()).digest("hex");
      const id1 = randomUUID();

      // Direct insert with new dedicated columns
      const insertSql = `
        INSERT INTO media_assets (
          id, workspace_id, source_type, is_ai_generated, url, storage_key,
          prompt, model_name, seed, cost_usd, width, height,
          license, attribution, status, content_hash, alt_text
        ) VALUES (
          $1, $2, 'ai_generated', true, $3, $4,
          $5, $6, $7, $8, $9, $10,
          'ai_generated', 'Generated by Juggernaut XL v9', 'approved', $11, '[Ảnh minh họa AI] Migration 023'
        )
        ON CONFLICT (workspace_id, content_hash) WHERE content_hash IS NOT NULL
        DO UPDATE SET updated_at = NOW()
        RETURNING *;
      `;

      const res1 = await client.query(insertSql, [
        id1,
        TRIPC_WORKSPACE,
        "http://localhost:3000/uploads/test.webp",
        "generated/test.webp",
        "High-end resort interior",
        "Juggernaut XL v9",
        12345,
        0.0,
        1024,
        1024,
        testHash,
      ]);

      expect(res1.rows[0].model_name).toBe("Juggernaut XL v9");
      expect(res1.rows[0].seed).toBe("12345");
      expect(parseFloat(res1.rows[0].cost_usd)).toBe(0.0);
      expect(res1.rows[0].width).toBe(1024);
      expect(res1.rows[0].height).toBe(1024);
      expect(res1.rows[0].is_ai_generated).toBe(true);
      expect(res1.rows[0].storage_key).toBe("generated/test.webp");

      // Idempotent duplicate insert with different ID -> ON CONFLICT resolves without error
      const id2 = randomUUID();
      const res2 = await client.query(insertSql, [
        id2,
        TRIPC_WORKSPACE,
        "http://localhost:3000/uploads/test.webp",
        "generated/test.webp",
        "High-end resort interior",
        "Juggernaut XL v9",
        12345,
        0.0,
        1024,
        1024,
        testHash,
      ]);

      expect(res2.rows[0].id).toBe(id1); // Preserves original row ID

      // Rollback transaction so public table remains in original un-migrated state
      await client.query("ROLLBACK");
    } finally {
      client.release();
    }
  });
});

